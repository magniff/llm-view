"""Generate engine/src/unicode_tables.rs: the code point ranges of \\p{L}.

The GPT-2 pre-tokenizer regex uses \\p{L} (General_Category = Letter). Rust's
`char::is_alphabetic` is the broader Alphabetic property, which also covers
combining vowel signs (Mn/Mc) and circled letters (So), so it splits
differently from HF on e.g. Devanagari. We ship the exact table instead.

    .venv/bin/python reference/gen_unicode_tables.py
"""

import os
import sys
import unicodedata

ranges = []
for cp in range(sys.maxunicode + 1):
    if unicodedata.category(chr(cp)).startswith("L"):
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])

out = os.path.join(os.path.dirname(__file__), "..", "engine", "src", "unicode_tables.rs")
with open(out, "w") as f:
    f.write(f"//! Generated by reference/gen_unicode_tables.py from Unicode "
            f"{unicodedata.unidata_version}. Do not edit.\n\n")
    f.write("/// Inclusive ranges of General_Category L (Lu Ll Lt Lm Lo), sorted.\n")
    f.write(f"pub static LETTER: [(u32, u32); {len(ranges)}] = [\n")
    for a, b in ranges:
        f.write(f"    (0x{a:04X}, 0x{b:04X}),\n")
    f.write("];\n")
print(f"{len(ranges)} ranges -> {os.path.normpath(out)}")
